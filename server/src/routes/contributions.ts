import {
  contributionCreateSchema,
  contributionUpdateSchema,
  contributionListQuery,
  type ContributionListQuery,
} from "@makthab/shared";
import { contributionRepository } from "../db";
import { asyncHandler } from "../lib/asyncHandler";
import { validateBody, validateQuery } from "../middleware/validate";
import { requireAuth, requireModuleAccessOrReportsView, requireResourcePermission } from "../middleware/auth";
import { AppError } from "../middleware/errorHandler";
import { actorStaffId } from "../lib/actor";
import { nextContributionReceiptNo } from "../lib/docNo";
